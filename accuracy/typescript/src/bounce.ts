// Prints accuracy/BOUNCE.md: where Lux Studio's bounced light differed from
// Radiance's, and what luminaire bodies change (ADRs 0070, 0075). Bounced
// light, total less direct, read a little high in almost every room: in
// Radiance a luminaire's glowing surface hides bounced light, as a black body
// would. The study compares bounced light with luminaire bodies off and on,
// then checks what's left against the patch size, and looks again at the
// sconce's split-openings step. `npm run accuracy:bounce` bundles this with
// Vite and runs it in Node.
import { DEFAULT_CALCULATION_OPTIONS, type CalculationOptions } from '@luxstudio/core';
import {
  compareReference,
  oursLx,
  radianceLx,
  summarize,
  type PointComparison,
  type Reference,
} from './compare';
import { IES_FILES, REFERENCES } from './inputs';

const WITHOUT_BODIES = { ...DEFAULT_CALCULATION_OPTIONS, luminaireBodies: false };

/** Each surface's bounced-light average difference, over the points the app counts. */
function bouncedAverages(points: readonly PointComparison[]): Map<string, number> {
  const sums = new Map<string, { radiance: number; ours: number }>();
  for (const point of points) {
    if (point.covered) continue;
    const sum = sums.get(point.surface) ?? { radiance: 0, ours: 0 };
    sum.radiance += radianceLx(point, 'bounced');
    sum.ours += oursLx(point, 'bounced');
    sums.set(point.surface, sum);
  }
  return new Map([...sums].map(([surface, s]) => [surface, s.ours / s.radiance - 1]));
}

const compare = (reference: Reference, options: CalculationOptions) =>
  compareReference(reference, IES_FILES, options);
const signed = (value: number) => `${value >= 0 ? '+' : ''}${(value * 100).toFixed(2)} %`;
const percent = (value: number) => `${(value * 100).toFixed(2)} %`;
const mean = (values: readonly number[]) => values.reduce((s, v) => s + v, 0) / values.length;
const worstTotalAverage = (points: readonly PointComparison[], reference: Reference) =>
  Math.max(
    ...summarize(
      points,
      reference.room.luminaires.map((l) => l.origin),
      'total',
    ).map((s) => Math.abs(s.averageError)),
  );

// --- 1. Bounced light, without and with luminaire bodies. ---
const excessRows: string[] = [];
const withoutAll: number[] = [];
const withAll: number[] = [];
for (const [name, reference] of Object.entries(REFERENCES)) {
  const without = bouncedAverages(compare(reference, WITHOUT_BODIES));
  const withBodies = bouncedAverages(compare(reference, DEFAULT_CALCULATION_OPTIONS));
  for (const [surface, error] of without) {
    const after = withBodies.get(surface)!;
    withoutAll.push(error);
    withAll.push(after);
    excessRows.push(`| ${name} | ${surface} | ${signed(error)} | ${signed(after)} |`);
  }
}

// --- 2. What's left, against the patch size. ---
const PATCHES_M = [0.5, 0.25, 0.125];
const patchRows = PATCHES_M.map((patchSizeM) => {
  const errors = Object.values(REFERENCES).flatMap((reference) => [
    ...bouncedAverages(compare(reference, { ...DEFAULT_CALCULATION_OPTIONS, patchSizeM })).values(),
  ]);
  const size =
    patchSizeM === DEFAULT_CALCULATION_OPTIONS.patchSizeM ? `${patchSizeM} (default)` : patchSizeM;
  return (
    `| ${size} | ${signed(mean(errors))} | ${percent(mean(errors.map(Math.abs)))} | ` +
    `${percent(Math.max(...errors.map(Math.abs)))} |`
  );
});

// --- 3. The sconce's split-openings step. ---
const sconce = REFERENCES['wall-sconce']!;
const sconceRows = (
  [
    ['Without luminaire bodies', WITHOUT_BODIES],
    ['With luminaire bodies', DEFAULT_CALCULATION_OPTIONS],
  ] as const
).map(([label, options]) => {
  const whole = worstTotalAverage(compare(sconce, { ...options, splitOpenings: false }), sconce);
  const cells = worstTotalAverage(compare(sconce, options), sconce);
  return `| ${label} | ${percent(whole)} | ${percent(cells)} |`;
});

const lines = [
  '# Bounced light: where the difference came from',
  '',
  'Generated by `npm run accuracy:bounce` (ADRs 0070, 0075). Bounced light is total less',
  'direct, on both sides, over the points the app counts (ADR 0074).',
  '',
  '## Luminaire bodies',
  '',
  "Each surface's bounced-light average against Radiance's, with luminaire bodies off and",
  "on: on, each luminaire's body (its IES opening, as a black box) hides bounced light,",
  'as a glowing surface does in Radiance. On is the default.',
  '',
  '| Room | Surface | Without bodies | With bodies |',
  '|---|---|---|---|',
  ...excessRows,
  `| **Mean** | | ${signed(mean(withoutAll))} | ${signed(mean(withAll))} |`,
  `| **Mean of the sizes** | | ${percent(mean(withoutAll.map(Math.abs)))} | ${percent(mean(withAll.map(Math.abs)))} |`,
  '',
  "## What's left, against the patch size",
  '',
  "With bodies, over every room's surfaces. A bias that shrinks with the patches is the",
  "patches'; one that doesn't is elsewhere.",
  '',
  '| Patch size (m) | Mean difference | Mean size | Worst |',
  '|---|---|---|---|',
  ...patchRows,
  '',
  "## The sconce's split-openings step",
  '',
  "The worst total-light surface average, with the sconce's 23 × 13 × 51 cm box as one",
  'point and split into cells.',
  '',
  '| | One point | Split into cells |',
  '|---|---|---|',
  ...sconceRows,
];
console.log(lines.join('\n'));
