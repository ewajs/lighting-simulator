// Prints accuracy/PATCH-SIZE.md: how the patch size for bounced light trades
// accuracy against time, over every reference room (ADR 0060). It's the
// evidence for the default `patchSizeM`. `npm run accuracy:patch-size`
// bundles this with Vite and runs it in Node; the times are this machine's.
import { DEFAULT_CALCULATION_OPTIONS } from '@luxstudio/core';
import { compareReference, summarize } from './compare';
import { IES_FILES, REFERENCES } from './inputs';

const SIZES_M = [0.5, 0.25, 0.125];
/** The default room, 5 × 4 × 2.7 m, to count its patches. */
const ROOM_M = { width: 5, depth: 4, height: 2.7 };

const percent = (value: number) => `${(value * 100).toFixed(2)} %`;
const rooms = Object.keys(REFERENCES);

const summaryRows: string[] = [];
const roomRows: string[] = [];
for (const patchSizeM of SIZES_M) {
  const options = { ...DEFAULT_CALCULATION_OPTIONS, patchSizeM };
  let worstAverage = 0;
  let worstFar = 0;
  const farByRoom: number[] = [];
  const start = performance.now();
  for (const reference of Object.values(REFERENCES)) {
    // Without furniture where a room has it: Lux Studio's bounced light passes
    // through furniture, so this measures the patches alone.
    const points = compareReference(reference, IES_FILES, options, !reference.withoutFurniture);
    const origins = reference.room.luminaires.map((luminaire) => luminaire.origin);
    let roomFar = 0;
    for (const surface of summarize(points, origins, 'total')) {
      worstAverage = Math.max(worstAverage, Math.abs(surface.averageError));
      roomFar = Math.max(roomFar, surface.worstFar);
    }
    worstFar = Math.max(worstFar, roomFar);
    farByRoom.push(roomFar);
  }
  const seconds = (performance.now() - start) / 1000;
  const side = (lengthM: number) => Math.ceil(lengthM / patchSizeM);
  const { width, depth, height } = ROOM_M;
  const patches =
    2 * side(width) * side(depth) + 2 * side(width) * side(height) + 2 * side(depth) * side(height);
  const size =
    patchSizeM === DEFAULT_CALCULATION_OPTIONS.patchSizeM ? `${patchSizeM} (default)` : patchSizeM;
  summaryRows.push(
    `| ${size} | ${patches} | ${percent(worstAverage)} | ${percent(worstFar)} | ${seconds.toFixed(1)} |`,
  );
  roomRows.push(`| ${size} | ${farByRoom.map(percent).join(' | ')} |`);
}

const lines = [
  '# Patch size: accuracy against time',
  '',
  'Generated by `npm run accuracy:patch-size` (ADR 0060): total light against Radiance',
  'over every reference room, for each patch size. Furnished rooms are compared without',
  "their furniture, on both sides, since Lux Studio's bounced light passes through it.",
  '"Average" is the worst surface average\'s difference; "far point" the worst bright',
  'point at least 1 m from a luminaire. Times are the whole calculation for all rooms, on',
  'the machine that ran it.',
  '',
  '| Patch size (m) | Patches, 5 × 4 × 2.7 m room | Worst average | Worst far point | Time, all rooms (s) |',
  '|---|---|---|---|---|',
  ...summaryRows,
  '',
  '## Worst far point, room by room',
  '',
  `| Patch size (m) | ${rooms.join(' | ')} |`,
  `|---|${rooms.map(() => '---').join('|')}|`,
  ...roomRows,
];
console.log(lines.join('\n'));
